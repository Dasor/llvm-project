def describe(cfg):
    return (f"C[{cfg.M}x{cfg.N}] = A[{cfg.M}x{cfg.K}] @ B[{cfg.K}x{cfg.N}], "
            f"L1 tile {cfg.m}x{cfg.n}x{cfg.k} (MxNxK), {CORES} cores, "
            f"{'dual-buffered' if cfg.pipelined else 'not pipelined'}, "
            f"{cfg.microkernel} microkernel, {cfg.simulator}")


def main(argv=None):
    cfg = parse_args(argv)
    try:
        validate(cfg)
        env = load_env()
        check_tools(cfg, env)

        work = Path(env["OUT"]) / cfg.name
        work.mkdir(parents=True, exist_ok=True)
        r = Runner(env, work)
        print(f"[*] {describe(cfg)}\n[*] work dir: {work}", flush=True)

        mlir = gen_matmul_mlir(cfg, r.path("matmul.mlir"))
        mlir = tile_and_promote(cfg, r, mlir)
        mlir = form_microkernels(r, mlir)
        mlir = bufferize(cfg, r, mlir)
        mlir = lower_l1_and_dma(r, mlir)
        mlir = convert_to_riscv(r, mlir)
        llvm_mlir = lower_to_llvm(r, mlir)
        llvm_obj = llvm_to_object(r, llvm_mlir)
        kernel_objs = build_microkernels(cfg, r, llvm_mlir)
        elf = link_executable(cfg, r, llvm_obj, kernel_objs)

        status, log = run_simulator(cfg, r, elf)
        check_result(cfg, status, log)
    except PipelineError as e:
        print(f"[!] {e}", file=sys.stderr)
        return 1

    verdict = "verified" if cfg.verify else "ran (not verified)"
    print(f"[+] {verdict}: {describe(cfg)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
