def load_env():
    """Source env.sh (the single source of truth for tool paths) and return
    the resulting environment."""
    out = subprocess.run(
        ["bash", "-c", f'source "{SB_ROOT}/env.sh" && env -0'],
        check=True, capture_output=True).stdout
    env = {}
    for entry in out.split(b"\0"):
        if b"=" in entry:
            key, _, val = entry.partition(b"=")
            env[key.decode()] = val.decode()
    return env


def which(tool, env):
    for d in env.get("PATH", "").split(os.pathsep):
        cand = Path(d) / tool
        if cand.is_file() and os.access(cand, os.X_OK):
            return cand
    return None


def check_tools(cfg, env):
    required = {
        env["MLIR_OPT"]: "run ./build.sh first",
        env["MLIR_TRANSLATE"]: "run ./build.sh first",
        env["LLC"]: "run ./build.sh first",
        env["XDSL_OPT"]: "run ./build.sh first",
        f"{env['TOOLCHAIN']}/bin/clang": "set QUIDDITCH_TOOLCHAIN (see README)",
        f"{env['TOOLCHAIN']}/bin/ld.lld": "set QUIDDITCH_TOOLCHAIN (see README)",
    }
    if cfg.microkernel == "xdsl":
        required[f"{env['TOOLCHAIN']}/bin/pulp-as"] = "set QUIDDITCH_TOOLCHAIN (see README)"
    else:
        required[f"{env['SNITCH_TOOLCHAIN']}/bin/clang"] = \
            "rebuild the docker image (Dockerfile's snitch_toolchain stage)"
    if cfg.simulator == "verilator":
        required[env["SNITCH_CLUSTER_VLT"]] = "run ./build.sh --verilator first"
        if cfg.verify:
            required[f"{env['VENV']}/bin/python3"] = "run ./build.sh first"

    missing = [f"{p} not found -- {hint}" for p, hint in required.items()
               if not os.access(p, os.X_OK)]
    if not Path(env["SNRT"], "lib", "libsnRuntime.a").is_file():
        missing.append(f"{env['SNRT']}/lib/libsnRuntime.a not found -- run ./build.sh first")
    if cfg.microkernel == "library":
        sw = Path(env["SNITCH_CLUSTER_ROOT"], "sw")
        if not (sw / "runtime/impl/snitch_cluster_cfg.h").is_file():
            missing.append(f"{sw}/runtime/impl/snitch_cluster_cfg.h not found -- generated "
                           "by ./build.sh --verilator, needed by the library microkernel")
        if not (sw / UPSTREAM_GEMM).is_file():
            missing.append(f"{sw / UPSTREAM_GEMM} not found -- snitch_cluster submodule missing?")
    if cfg.simulator == "verilator" and cfg.verify:
        snitch_sim = Path(env["SNITCH_CLUSTER_ROOT"], "util/sim/SnitchSim.py")
        if not snitch_sim.is_file():
            missing.append(f"{snitch_sim} not found -- snitch_cluster submodule missing?")
    if cfg.simulator == "gvsoc" and which("gvrun", env) is None:
        missing.append("gvrun not on PATH -- run ./build.sh first")
    if missing:
        raise PipelineError("missing tools:\n  " + "\n  ".join(missing))


