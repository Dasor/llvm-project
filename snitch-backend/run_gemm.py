def stream(cmd, env, cwd, log):
    """Run cmd, teeing its combined output to stdout and log; return the exit status."""
    with open(log, "w") as f:
        proc = subprocess.Popen([str(c) for c in cmd], env=env, cwd=cwd,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in proc.stdout:
            sys.stdout.write(line)
            f.write(line)
        return proc.wait()


def run_gvsoc(r, elf):
    sim_dir = r.path("gvsoc")
    sim_dir.mkdir(exist_ok=True)
    log = sim_dir / "run.log"
    status = stream(["gvrun", "--target", "snitch", "--work-dir", sim_dir,
                     "--param", f"chip/soc/binary={elf}", "run"], r.env, None, log)
    return status, log


def run_verilator(cfg, r, elf):
    sim_dir = r.path("verilator")
    sim_dir.mkdir(exist_ok=True)
    log = sim_dir / "run.log"
    cmd = [verilator_model(r.env), elf]
    if cfg.verify:
        # Launches the model itself and checks C on the host over IPC.
        cmd = [f"{r.env['VENV']}/bin/python3", SB_ROOT / "verify_gemm_ipc.py", *cmd,
               cfg.M, cfg.N, cfg.K, "--mismatch-csv", sim_dir / "mismatches.csv"]
    # The Verilator model writes its traces/logs into the current directory.
    status = stream(cmd, r.env, sim_dir, log)
    return status, log


def run_simulator(cfg, r, elf):
    print(f"[*] run on {cfg.simulator}", flush=True)
    if cfg.simulator == "gvsoc":
        return run_gvsoc(r, elf)
    return run_verilator(cfg, r, elf)


def check_result(cfg, status, log):
    if status != 0:
        raise PipelineError(f"{cfg.simulator} exited with status {status} (log: {log})")
    if cfg.verify:
        expected = f"all {cfg.M * cfg.N} values matched"
        if expected not in log.read_text():
            raise PipelineError(f"did not find '{expected}' in {cfg.simulator} output "
                                f"(log: {log})")


