def positive_int(s):
    v = int(s)
    if v <= 0:
        raise argparse.ArgumentTypeError(f"expected a positive integer, got {s}")
    return v


def boolean(s):
    if s not in ("true", "false"):
        raise argparse.ArgumentTypeError(f"expected 'true' or 'false', got '{s}'")
    return s == "true"


def parse_args(argv=None):
    p = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    for name, help_ in [("N", "columns of B and C"), ("M", "rows of A and C"),
                        ("K", "reduction dimension"), ("n", "L1 tile size along N"),
                        ("m", "L1 tile size along M"), ("k", "L1 tile size along K")]:
        p.add_argument(name, type=positive_int, help=help_)
    p.add_argument("pipelined", type=boolean)
    p.add_argument("simulator", choices=["gvsoc", "verilator"])
    p.add_argument("microkernel", choices=["xdsl", "library"])
    p.add_argument("verify", type=boolean)
    return Config(**vars(p.parse_args(argv)))


def validate(cfg):
    errors = []
    for tile, dim, t, d in [("m", "M", cfg.m, cfg.M), ("n", "N", cfg.n, cfg.N),
                            ("k", "K", cfg.k, cfg.K)]:
        if t > d:
            errors.append(f"tile {tile}={t} is larger than {dim}={d}")
    # Current compiler limitations (found empirically): with no tiling loop
    # left, bufferization of the L1 copy of C fails ("would write to read-only
    # buffer"); dual-buffering additionally needs at least two tiled loops,
    # otherwise snitch.pipeline fails to bufferize (or, with none, no pipeline
    # is formed at all).
    split = sum(t < d for t, d in [(cfg.m, cfg.M), (cfg.n, cfg.N), (cfg.k, cfg.K)])
    min_split = 2 if cfg.pipelined else 1
    if split < min_split:
        errors.append(f"{'pipelined' if cfg.pipelined else 'non-pipelined'} mode needs "
                      f"at least {min_split} of M, N, K split into more than one tile "
                      f"(tile < dimension), got {split}")
    if cfg.m % CORES:
        errors.append(f"m={cfg.m} must be a multiple of the {CORES} compute cores "
                      f"(thread-tiling along M)")
    if cfg.microkernel == "library":
        if cfg.n % LIBRARY_UNROLL:
            errors.append(f"library microkernel needs n % {LIBRARY_UNROLL} == 0, "
                          f"got n={cfg.n}")
        if cfg.k < 2:
            errors.append(f"library microkernel needs k >= 2, got k={cfg.k}")
    if errors:
        raise PipelineError("invalid configuration:\n  " + "\n  ".join(errors))


