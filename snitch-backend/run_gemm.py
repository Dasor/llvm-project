def transform(r, stage, src, dst, library):
    return r.mlir_opt(stage, src, dst,
                      f"--transform-preload-library=transform-library-paths={library}",
                      "--transform-interpreter", "--cse", "--canonicalize")


def tile_and_promote(cfg, r, src):
    """L1 tiling, L1 promotion and (if pipelined) pipeline formation, then
    thread-tiling. Promotion/pipelining must precede thread-tiling so all
    cores share one DMA'd-in L1 tile."""
    tiled = transform(r, "tile to L1", src, r.path("step1a_l1_tiled.mlir"),
                      gen_tile_transform(cfg, r.path("tile_l1.mlir")))
    # promote-pads-to-l1 must run before promote-operands-to-l1 so the
    # padded tile's L1 copy is the padding-aware fused DMA copy.
    promoted = r.mlir_opt(
        "promote pads and operands to L1", tiled, r.path("step1b_promoted.mlir"),
        "--pass-pipeline=builtin.module(func.func(snitch-promote-pads-to-l1,"
        "snitch-promote-operands-to-l1,cse,canonicalize))")
    if cfg.pipelined:
        promoted = r.mlir_opt(
            "form copy/compute pipeline", promoted, r.path("step1c_pipeline.mlir"),
            "--pass-pipeline=builtin.module(func.func(snitch-pipeline-copy-compute))")
        # The tensor-level ordering (pipeline-copy-compute strictly before
        # thread-tiling) is load-bearing and fails silently if reversed.
        count = promoted.read_text().count("snitch.pipeline ")
        if count != 1:
            raise PipelineError(f"expected exactly 1 snitch.pipeline op after "
                                f"pipelining, got {count}")
    return transform(r, f"thread-tile across {CORES} cores", promoted,
                     r.path("step1d_thread_tiled.mlir"),
                     gen_thread_tile_transform(r.path("tile_threads.mlir")))


def form_microkernels(r, src):
    return r.mlir_opt(
        "form microkernels", src, r.path("step1e_microkernels.mlir"),
        "--pass-pipeline=builtin.module(func.func("
        "snitch-form-microkernels,snitch-eliminate-empty-tensors))")


def bufferize(cfg, r, src):
    out = r.mlir_opt("bufferize", src, r.path("step2a_bufferized.mlir"),
                     "--snitch-bufferize=use-dma-memcpy=true", "--cse", "--canonicalize")
    if cfg.pipelined:
        out = r.mlir_opt("lower pipeline op", out, r.path("step2b_pipeline_lowered.mlir"),
                         "--snitch-lower-pipeline-op", "--cse", "--canonicalize")
    return r.mlir_opt("lower scf.forall", out, r.path("step2c_forall_lowered.mlir"),
                      f"--snitch-lower-forall-op=compute-cores={CORES}",
                      "--cse", "--canonicalize")


def lower_l1_and_dma(r, src):
    # assert-compiled: a tile that overflows L1 is a hard error instead of a
    # warning that silently drops the kernel body.
    return r.mlir_opt(
        "lower L1 allocations and DMA", src, r.path("step3_l1_dma.mlir"),
        "--pass-pipeline=builtin.module(func.func("
        "snitch-lower-l1-allocations{assert-compiled=true}),"
        "cse,canonicalize,snitch-specialize-dma-code,"
        "func.func(snitch-dma-legalize-dma-operations,cse,canonicalize))")


def convert_to_riscv(r, src):
    """xDSL's convert-to-riscv. Always runs: it fixes the microkernels' symbol
    names/signatures even when the library microkernel replaces their body."""
    gen = r.mlir_opt("generalize named ops", src, r.path("step4_generalized.mlir"),
                     "--linalg-generalize-named-ops")
    return r.mlir_opt(
        "convert to riscv (xDSL)", gen, r.path("step5_riscv.mlir"),
        "--pass-pipeline=builtin.module(convert-to-riscv{"
        f"xdsl-opt-path={r.env['XDSL_OPT']} assert-compiled=true}})")


def lower_to_llvm(r, src):
    return r.mlir_opt(
        "lower to LLVM dialect", src, r.path("step6_llvm.mlir"),
        "--convert-scf-to-cf",
        f"--convert-snitch-to-llvm=barrier-participants={BARRIER_PARTICIPANTS}",
        "--convert-dma-to-llvm", "--expand-strided-metadata", "--lower-affine",
        f"--finalize-memref-to-llvm={INDEX_BW}", f"--convert-arith-to-llvm={INDEX_BW}",
        f"--convert-cf-to-llvm={INDEX_BW}",
        f"--convert-func-to-llvm={INDEX_BW} use-bare-ptr-memref-call-conv=true",
        "--reconcile-unrealized-casts")


def llvm_to_object(r, src):
    ll = r.path("matmul.ll")
    obj = r.path("matmul_llvm.o")
    r.run("translate to LLVM IR",
          [r.env["MLIR_TRANSLATE"], "--mlir-to-llvmir", src, "-o", ll])
    r.run("compile LLVM IR (llc)", [r.env["LLC"], *LLC_FLAGS, "-o", obj, ll])
    return obj


