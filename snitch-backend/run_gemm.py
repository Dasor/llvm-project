def stream(cmd, env, cwd, log):
    """Run cmd, teeing its combined output to stdout and log; return the exit status."""
    with open(log, "w") as f:
        proc = subprocess.Popen([str(c) for c in cmd], env=env, cwd=cwd,
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        for line in proc.stdout:
            sys.stdout.write(line)
            f.write(line)
        return proc.wait()


def run_gvsoc(r, elf):
    sim_dir = r.path("gvsoc")
    sim_dir.mkdir(exist_ok=True)
    log = sim_dir / "run.log"
    status = stream(["gvrun", "--target", "snitch", "--work-dir", sim_dir,
                     "--param", f"chip/soc/binary={elf}", "run"], r.env, None, log)
    return status, log


def run_verilator(cfg, r, elf):
    sim_dir = r.path("verilator")
    sim_dir.mkdir(exist_ok=True)
    log = sim_dir / "run.log"
    cmd = [r.env["SNITCH_CLUSTER_VLT"], elf]
    if cfg.verify:
        # Launches the model itself and checks C on the host over IPC.
        cmd = [f"{r.env['VENV']}/bin/python3", SB_ROOT / "verify_gemm_ipc.py", *cmd,
               cfg.M, cfg.N, cfg.K, "--mismatch-csv", sim_dir / "mismatches.csv"]
    # The Verilator model writes its traces/logs into the current directory.
    status = stream(cmd, r.env, sim_dir, log)
    return status, log


def run_simulator(cfg, r, elf):
    print(f"[*] run on {cfg.simulator}", flush=True)
    if cfg.simulator == "gvsoc":
        return run_gvsoc(r, elf)
    return run_verilator(cfg, r, elf)


def check_result(cfg, status, log):
    if status != 0:
        raise PipelineError(f"{cfg.simulator} exited with status {status} (log: {log})")
    if cfg.verify:
        expected = f"all {cfg.M * cfg.N} values matched"
        if expected not in log.read_text():
            raise PipelineError(f"did not find '{expected}' in {cfg.simulator} output "
                                f"(log: {log})")


# --------------------------------------------------------------------------

def describe(cfg):
    return (f"C[{cfg.M}x{cfg.N}] = A[{cfg.M}x{cfg.K}] @ B[{cfg.K}x{cfg.N}], "
            f"L1 tile {cfg.m}x{cfg.n}x{cfg.k} (MxNxK), {CORES} cores, "
            f"{'dual-buffered' if cfg.pipelined else 'not pipelined'}, "
            f"{cfg.microkernel} microkernel, {cfg.simulator}")


def main(argv=None):
    cfg = parse_args(argv)
    try:
        validate(cfg)
        env = load_env()
        check_tools(cfg, env)

        work = Path(env["OUT"]) / cfg.name
        work.mkdir(parents=True, exist_ok=True)
        r = Runner(env, work)
        print(f"[*] {describe(cfg)}\n[*] work dir: {work}", flush=True)

        mlir = gen_matmul_mlir(cfg, r.path("matmul.mlir"))
        mlir = tile_and_promote(cfg, r, mlir)
        mlir = form_microkernels(r, mlir)
        mlir = bufferize(cfg, r, mlir)
        mlir = lower_l1_and_dma(r, mlir)
        mlir = convert_to_riscv(r, mlir)
        llvm_mlir = lower_to_llvm(r, mlir)
        llvm_obj = llvm_to_object(r, llvm_mlir)
        kernel_objs = build_microkernels(cfg, r, llvm_mlir)
        elf = link_executable(cfg, r, llvm_obj, kernel_objs)

        status, log = run_simulator(cfg, r, elf)
        check_result(cfg, status, log)
    except PipelineError as e:
        print(f"[!] {e}", file=sys.stderr)
        return 1

    verdict = "verified" if cfg.verify else "ran (not verified)"
    print(f"[+] {verdict}: {describe(cfg)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
