class Runner:
    def __init__(self, env, work):
        self.env = env
        self.work = work

    def run(self, stage, cmd, cwd=None):
        print(f"[*] {stage}", flush=True)
        res = subprocess.run([str(c) for c in cmd], env=self.env, cwd=cwd,
                             capture_output=True, text=True)
        if res.returncode != 0:
            sys.stderr.write(res.stdout + res.stderr)
            raise PipelineError(f"stage '{stage}' failed (exit {res.returncode}): "
                                + " ".join(str(c) for c in cmd))
        return res.stdout

    def mlir_opt(self, stage, src, dst, *args):
        self.run(stage, [self.env["MLIR_OPT"], *args, src, "-o", dst])
        return dst

    def path(self, name):
        return self.work / name


