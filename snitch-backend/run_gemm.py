def kernel_symbols(llvm_mlir):
    """The microkernel symbols the lowered module calls (matmul$xdsl_kernelN)."""
    syms = sorted(set(re.findall(r"@\"?(matmul\$xdsl_kernel\d+)",
                                 llvm_mlir.read_text())))
    if not syms:
        raise PipelineError(f"no matmul$xdsl_kernelN symbols found in {llvm_mlir}")
    return syms


def build_xdsl_kernels(r, llvm_mlir):
    for old in r.work.glob("xdsl_kernel*.[So]"):
        old.unlink()
    r.run("extract xDSL assembly",
          ["python3", SB_ROOT / "extract_asm.py", llvm_mlir, r.path("xdsl_kernel")])
    objs = []
    for s in sorted(r.work.glob("xdsl_kernel*.S")):
        o = s.with_suffix(".o")
        r.run(f"assemble {s.name}",
              [f"{r.env['TOOLCHAIN']}/bin/pulp-as", "--filetype=obj",
               "--target-abi=ilp32d", s, "-o", o, "--mcpu=snitch", "-g"])
        objs.append(o)
    return objs


def patch_upstream_gemm(r):
    """Copy snitch_cluster's gemm_fp64.h into the work dir with the one fix it
    needs to compile: an input operand declared with the output constraint
    "=r", which $SNITCH_TOOLCHAIN's clang rejects. The copy is searched before
    the submodule, which stays untouched. Once fixed upstream this is a no-op."""
    src = Path(r.env["SNITCH_CLUSTER_ROOT"], "sw", UPSTREAM_GEMM)
    text = src.read_text()
    bad = '[ c ] "=r"(&C[m * ldc + n0 * unroll])'
    if text.count(bad) > 1:
        raise PipelineError(f"unexpected upstream layout in {src}: {bad} occurs more than once")
    inc = r.path("upstream_include")
    inc.mkdir(exist_ok=True)
    (inc / "gemm_fp64.h").write_text(text.replace(bad, '[ c ] "r"(&C[m * ldc + n0 * unroll])'))
    return inc


def build_library_kernels(cfg, r, llvm_mlir):
    sw = Path(r.env["SNITCH_CLUSTER_ROOT"], "sw")
    includes = [f"-I{patch_upstream_gemm(r)}", *(f"-I{sw / d}" for d in SNITCH_SW_INCLUDES)]
    defines = [f"-DTILE_M={cfg.m // CORES}", f"-DTILE_N={cfg.n}", f"-DTILE_K={cfg.k}"]
    if cfg.simulator == "gvsoc":
        # See gemm_library_kernel.cpp: gvsoc drops SSR write-stream values
        # still queued when SSR is disabled.
        defines.append("-DSSR_DRAIN_WORKAROUND")
    objs = []
    for sym in kernel_symbols(llvm_mlir):
        o = r.path(f"library_{sym.split('$')[-1]}.o")
        r.run(f"compile library microkernel as {sym}",
              [f"{r.env['SNITCH_TOOLCHAIN']}/bin/clang", *SNITCH_CLANG_FLAGS, *includes,
               *defines, f'-DKERNEL_SYMBOL="{sym}"', "-c",
               f"{r.env['KERNELS']}/gemm_library_kernel.cpp", "-o", o])
        objs.append(o)
    return objs


def build_microkernels(cfg, r, llvm_mlir):
    if cfg.microkernel == "xdsl":
        return build_xdsl_kernels(r, llvm_mlir)
    return build_library_kernels(cfg, r, llvm_mlir)


