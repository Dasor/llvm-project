def link_executable(cfg, r, llvm_obj, kernel_objs):
    tc = r.env["TOOLCHAIN"]
    snrt = r.env["SNRT"]
    kernel = r.path("matmul_kernel.o")
    r.run("merge objects", [f"{tc}/bin/ld.lld", "-r", llvm_obj, *kernel_objs, "-o", kernel])

    main_obj = r.path("gemm_main.o")
    defines = [f"-DM={cfg.M}", f"-DN={cfg.N}", f"-DK={cfg.K}"]
    if cfg.verify and cfg.simulator == "gvsoc":
        # On Verilator, run_verilator verifies on the host instead.
        defines.append("-DVERIFY")
    r.run("compile gemm_main.c",
          [f"{tc}/bin/clang", "-isystem", f"{snrt}/include", *defines, *MAIN_CFLAGS,
           "-o", main_obj, "-c", f"{r.env['KERNELS']}/gemm_main.c"])

    elf = r.path("gemm.elf")
    r.run("link executable",
          [f"{tc}/bin/clang", "-g", "-O3", "-DNDEBUG", "-lm",
           "-T", f"{snrt}/ld/base.ld", f"-L{snrt}/ld",
           main_obj, kernel, "-o", elf, f"{snrt}/lib/libsnRuntime.a"])
    return elf


