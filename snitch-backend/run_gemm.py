#!/usr/bin/env python3
"""Compile and run a tiled f64 GEMM (C = A @ B) on the Snitch cluster.

    ./run_gemm.py <N> <M> <K> <n> <m> <k> <pipelined> <simulator> <microkernel> <verify>

A is MxK, B is KxN, C is MxN. (m, n, k) is the L1 tile size along (M, N, K);
m is further split across the compute cores (thread-tiling), so each hart's
microkernel works on an (m/CORES) x n x k tile.

  pipelined    true | false          dual-buffered DMA/compute pipelining
  simulator    gvsoc | verilator     fast ISS or cycle-accurate RTL model
  microkernel  xdsl | library        xDSL-generated asm, or the snitch_cluster
                                     C BLAS kernel (gemm_fp64.h, wrapped by
                                     kernels/gemm_library_kernel.cpp)
  verify       true | false          check C against a reference: on gvsoc, on
                                     the DM core; on verilator, on the host
                                     (verify_gemm_ipc.py reads C over the
                                     testbench's IPC interface, costing no
                                     simulated cycles)

Tool paths come from env.sh. Every intermediate is written to its own
per-configuration directory under $OUT, so runs never clobber each other.
"""
import argparse
import os
import re
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

SB_ROOT = Path(__file__).resolve().parent

# Hardware/pipeline constants that are still fixed (not command-line options).
CORES = 8                          # compute harts in the default Snitch cluster
BARRIER_PARTICIPANTS = CORES + 1   # compute harts + the DM hart
LIBRARY_UNROLL = 8                 # gemm_fp64_opt's unroll along N
PIPELINED_INTERCHANGE = [2, 0, 1]  # K outermost: snitch-pipeline-copy-compute
                                   # can't pipeline the reduction loop otherwise
ELEM_TYPE = "f64"

LLC_FLAGS = ["-mtriple=riscv32-unknown-unknown-elf", "-mcpu=generic-rv32",
             "-mattr=+m,+f,+d,+zfh", "-filetype=obj"]
SNITCH_CLANG_FLAGS = ["-O3", "-mcpu=snitch", "-menable-experimental-extensions",
                      "-mabi=ilp32d", "-mcmodel=medany", "-fno-common",
                      # snitch_cluster's runtime headers are C++, and
                      # __TOOLCHAIN_LLVM__ selects the SSR builtins in ssr.h.
                      "-std=gnu++17", "-fno-exceptions", "-fno-rtti",
                      "-D__TOOLCHAIN_LLVM__"]
# snitch_cluster/sw include dirs needed by snrt.h (runtime/impl holds the
# config headers generated by the Verilator build).
SNITCH_SW_INCLUDES = ["runtime/impl", "runtime/api", "runtime/api/omp",
                      "runtime/src", "runtime/src/omp", "deps/riscv-opcodes"]
UPSTREAM_GEMM = "kernels/blas/gemm/src/gemm_fp64.h"
MAIN_CFLAGS = ["-g", "-O3", "-DNDEBUG", "-std=gnu11", "-Wno-undefined-inline"]
INDEX_BW = "index-bitwidth=32"


@dataclass
class Config:
    N: int
    M: int
    K: int
    n: int
    m: int
    k: int
    pipelined: bool
    simulator: str
    microkernel: str
    verify: bool

    @property
    def name(self):
        pipe = "pipe" if self.pipelined else "nopipe"
        return (f"gemm_M{self.M}_N{self.N}_K{self.K}_t{self.m}x{self.n}x{self.k}"
                f"_{pipe}_{self.microkernel}")


class PipelineError(Exception):
    pass


